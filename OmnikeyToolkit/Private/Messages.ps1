function Set-MessageLanguage([string]$lang) {
    if (-not $script:MSG.ContainsKey($lang)) { $lang = 'en' }
    $script:M = $script:MSG[$lang]
}

function T([string]$key, $a0="", $a1="", $a2="", $a3="", $a4="", $a5="") { $script:M[$key] -f $a0,$a1,$a2,$a3,$a4,$a5 }
